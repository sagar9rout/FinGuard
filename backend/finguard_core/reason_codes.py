"""The reason-code registry (docs/engine/reason-codes.md).

The engine emits only these codes, with parameters, never free-form
prose (docs/engine/semantics.md Section 14). Renaming or removing a code
is a contract change requiring an ADR, per the registry's own status
note — this module is the single place codes are defined, so that rule
is enforced by code review on one file rather than hunted across the
package.
"""

